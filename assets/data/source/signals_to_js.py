#!/usr/bin/env python3
"""Build assets/data/signals.js from the eBPF sources in crates/kestrel-ebpf.

Emits `const SIGNALS = {...};` -- the load-as-a-script convention data.js,
campaigns.js and ebpf.js use, denormalised so the pages render without any
further joining: every map carries its declaration, its key and value shape,
and the programs that write it (producers) or read it (consumers) with the
call site that proves each edge.

THE SHAPE OF THE CRATE

  Three objects, each a unity build: src/host.c, src/net_sock.c and
  src/net_pkt.c include every shared source exactly once, so an object holds
  one copy of each map and every program in it shares them. A program is a
  SEC() entry function; 116 of them are listed in rust/contract.rs
  (CATALOGUE), one bit each in load_state.skipped.

WHAT IS PARSED

  * Each object's root, preprocessed the way clang sees it: #include lines
    followed in order (-I include -I src), #if/#ifdef/#else evaluated with
    the object's own KESTREL_OBJ_* define, KESTREL_TEST unset. The test
    fixtures (t_*, l0_selftest, l0_bench, t_own) therefore do not appear.
  * Every `SEC(".maps")` declaration left after that, per object. A map that
    survives in all three objects is one the loader creates once and shares
    by descriptor (docs/LOAD_CONTRACT.md section 1); one that survives in a
    single object belongs to that object.
  * Every SEC() program, written out or generated by a macro on a line of
    its own (L7_DECODER), with the comment above it.
  * Map-helper calls reached from a program through the object's static
    inline functions, its global (__noinline) functions, bpf_loop and
    bpf_timer callbacks and function-like macros. A WRITE is an update /
    delete / ringbuf output / timer init / storage get with F_CREATE, or a
    lookup whose result the same function writes through or returns as a
    writable pointer. Everything else that touches the map is a READ.

LIMITS, stated so the pages can state them

  * Reachability follows names: a callee passed as a value (a bpf_loop
    callback) is reached by its name appearing in the caller, which
    over-approximates slightly.
  * Userspace is not analysed. A map with in-kernel readers and no in-kernel
    writer is written by the loader or the daemon; one with writers and no
    readers is drained by userspace. Both are reported as such, and the load
    contract's own words about pinning and loader writes are carried in the
    family blurbs.

    python3 assets/data/source/signals_to_js.py \\
        ../crates/kestrel-ebpf assets/data/signals.js
"""
