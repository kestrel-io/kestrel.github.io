def mutates(body, var):
    v = re.escape(var)
    member = rf"{v}\s*(?:->|\.)\s*\w+(?:\s*\[[^\]]*\])?(?:\s*(?:->|\.)\s*\w+(?:\s*\[[^\]]*\])?)*"
    pats = [
        rf"\*\s*{v}\s*(?:\+\+|--|[-+*/|&^%]?=(?!=))",
        rf"\*\s*{v}\s*=\s*\(",
        rf"(?<![\w.>]){member}\s*(?:\+\+|--|[-+*/|&^%]?=(?!=))",
        rf"(?:\+\+|--)\s*\*?\s*(?:{member}|{v})\b",
        rf"__sync_fetch_and_\w+\s*\(\s*&\s*(?:{member}|{v})\s*[,)]",
        rf"{OUT_PARAM}\s*\(\s*&?\s*(?:{member}|{v})\s*[,)\[]",
        rf"\*\s*{v}\s*=\s*\(\s*(?:struct|union)\s+\w+\s*\)\s*\{{",
        # bpf_skb_load_bytes(ctx, off, DEST, len): the destination is third
        rf"bpf_skb_load_bytes\w*\s*\([^,]+,[^,]+,\s*&?\s*(?:{member}|{v})\s*[,)\[]",
    ]
    return any(re.search(p, body) for p in pats)

def scan_calls(body):
    for m in CALL.finditer(body):
        args, end = split_args(body, m.end())
        yield m.group(1), args, m.start(), end

KW_NOT_FN = {"if","for","while","switch","return","sizeof","do","else","case",
             "defined","__builtin_expect","typeof","_Static_assert"}

def functions_in(text):
    """name -> [(body, start)] for every function definition in `text`."""
    out = {}
    for m in re.finditer(r"\)\s*\{", text):
        j = m.start(); depth = 0; i = j
        while i >= 0:
            if text[i] == ")": depth += 1
            elif text[i] == "(":
                depth -= 1
                if depth == 0: break
            i -= 1
        if i < 0: continue
        k = i - 1
        while k >= 0 and text[k] in " \t\n\\": k -= 1
        e = k + 1
        while k >= 0 and (text[k].isalnum() or text[k] == "_"): k -= 1
        name = text[k + 1:e]
        if not name or name in KW_NOT_FN or name[0].isdigit(): continue
        q = k
        while q >= 0 and text[q] in " \t\n\\*": q -= 1
        if q < 0 or not (text[q].isalnum() or text[q] in "_>)"): continue
        if text[q] == ">" or (q > 0 and text[q - 1] == "."): continue
        o = m.end() - 1; depth = 0; jj = -1
        for t_ in range(o, len(text)):
            if text[t_] == "{": depth += 1
            elif text[t_] == "}":
                depth -= 1
                if depth == 0: jj = t_; break
        if jj <= o: continue
        params = [re.sub(r"\[.*", "", p.strip()).split()[-1].lstrip("*") if p.strip() and p.strip() != "void" else ""
                  for p in text[i + 1: j].split(",")]
        out.setdefault(name, []).append((text[o + 1: jj], k + 1, params))
    return out

