#!/usr/bin/env python3
"""Build assets/data/signals.js from the eBPF sources in crates/bpf.

Emits `const SIGNALS = {...};` -- the load-as-a-script convention data.js,
campaigns.js and ebpf.js use, denormalised so the pages render without any
further joining: every map carries its declaration, its key and value shape,
and the programs that write it (producers) or read it (consumers) with the
call site that proves each edge.

WHAT IS PARSED

  * Every `SEC(".maps")` declaration, whether written out in a header or a
    source or generated by a KESTREL_DEFINE_* / TELEMETRY_DEFINE_* macro
    (nested macros are expanded, so KESTREL_DEFINE_PATH_TABLE's side table
    appears under its own name).
  * Each program object's #include graph and its KESTREL_* feature gates,
    evaluated with a small #if/#ifdef evaluator, so a header's map belongs
    only to the objects that actually declare it.
  * Map-helper calls reached from a SEC() entry, a bpf_timer callback or a
    bpf_loop callback. A WRITE is an update / delete / push / ringbuf
    reserve / ringbuf output / storage get with F_CREATE, or a lookup whose
    result the same function writes through or returns as a writable
    pointer. Everything else that touches the map is a READ.

LIMITS, stated so the pages can state them

  * Gates only a kernel-capability probe sets (KESTREL_NO_*) are taken as
    unset: this is the capable-kernel build.
  * Reachability follows calls and macro bodies; a callee hidden behind
    token pasting is reached by name, which over-approximates slightly.
  * Userspace is not analysed. A map with in-kernel readers and no in-kernel
    writer is a control-plane input; one with writers and no readers is
    drained by userspace. Both are reported as such.

    python3 assets/data/source/signals_to_js.py \\
        ../crates/bpf assets/data/signals.js
"""
