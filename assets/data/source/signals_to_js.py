def family_of(name, macro):
    if name in NAMED: return NAMED[name]
    for rx, label, blurb in FAMILY:
        if re.search(rx, name): return label, blurb
    return "State", ""

def flow_of(rec):
    p, c = bool(rec["producers"]), bool(rec["consumers"])
    if p and c:  return "kernel-state"
    if p:        return "kernel-output"
    if c:        return "control-input"
    return "declared-only"

