def strip_comments(s):
    """Blank out comments, preserving every offset and newline."""
    out, i, n = list(s), 0, len(s)
    def blank(a, b):
        for k in range(a, b):
            if out[k] != "\n": out[k] = " "
    while i < n:
        if s.startswith("/*", i):
            j = s.find("*/", i + 2); j = n if j < 0 else j + 2
            blank(i, j); i = j
        elif s.startswith("//", i):
            j = s.find("\n", i); j = n if j < 0 else j
            blank(i, j); i = j
        elif s[i] in "\"'":
            q = s[i]; i += 1
            while i < n and s[i] != q:
                if s[i] == "\\": i += 1
                i += 1
            i += 1
        else:
            i += 1
    return "".join(out)

CODE = {p: strip_comments(t) for p, t in TEXT.items()}
lineno = lambda text, pos: text.count("\n", 0, pos) + 1

def clean_prose(body):
    lines = [re.sub(r"^\s*\*\s?", "", ln).strip() for ln in body.split("\n")]
    return re.sub(r"\s+", " ", " ".join(x for x in lines if x)).strip()

def doc_before(text, pos):
    """The comment block above `pos`, looking past #if/#define and blank lines."""
    head = text[:pos]
    skipped = 0
    while True:
        stripped = head.rstrip()
        if stripped.endswith("*/"):
            start = stripped.rfind("/*")
            if start < 0: return ""
            return clean_prose(stripped[start + 2: -2])
        nl = stripped.rfind("\n")
        line = stripped[nl + 1:].strip()
        if skipped >= 3 or (line and not re.match(r"#\s*(if|ifdef|ifndef|else|elif|endif|define)\b", line)):
            return ""
        skipped += 1
        head = stripped[:nl + 1]

# -------------------------------------------------------------- struct/enums
STRUCTS, ENUMS = {}, {}
FIELD_RE = re.compile(
    r"^(?P<type>(?:const |volatile |unsigned |signed |struct |union |enum )*"
    r"[A-Za-z_][A-Za-z_0-9]*\s*\**)\s*(?P<name>[A-Za-z_][A-Za-z_0-9]*)"
    r"(?P<arr>(?:\s*\[[^\]]*\])*)\s*(?::\s*(?P<bits>\d+))?$")
SKIP_TY = {"return", "if", "else", "static", "_Static_assert", "typedef"}

def comments_in(chunk):
    out = []
    for m in re.finditer(r"/\*(.*?)\*/|//([^\n]*)", chunk, re.S):
        out.append((m.start(), clean_prose(m.group(1) or m.group(2))))
    return out

def parse_struct_body(body):
    """Members of a struct, each with the comment the source keeps beside it.

    A comment on the same line as the PREVIOUS member's semicolon is that
    member's trailing note. A nested union or struct is flattened: its
    members are listed as the record's own, which is how the wire reads."""
    fields, bare, start = [], strip_comments(body), 0
    for m in re.finditer(r";", bare):
        raw, start = body[start:m.start()], m.end()
        if not raw.strip(): continue
        nl = raw.find("\n")
        notes, trailing = [], []
        for at, txt in comments_in(raw):
            (trailing if (nl >= 0 and at < nl) else notes).append(txt)
        if trailing and fields:
            fields[-1]["note"] = re.sub(r"\s+", " ",
                (fields[-1]["note"] + " " + " ".join(trailing)).strip())
        clean = re.sub(r"\s+", " ", strip_comments(raw)).strip()
        # a nested aggregate opens here: keep what follows its brace
        clean = re.sub(r"^(?:[^{}]*\{\s*)+", "", clean)
        clean = re.sub(r"^\}\s*\w*\s*", "", clean).strip()
        if not clean or "(" in clean: continue
        fm = FIELD_RE.match(clean)
        if not fm: continue
        ty = re.sub(r"\s+", " ", fm.group("type")).strip()
        if ty.split()[0] in SKIP_TY: continue
        fields.append({"type": ty,
                       "name": fm.group("name") + (fm.group("arr") or "").replace(" ", ""),
                       "bits": fm.group("bits"),
                       "note": re.sub(r"\s+", " ", " ".join(notes)).strip()})
    return fields

for p in ALL:
    t = TEXT[p]
    for m in re.finditer(r"\bstruct\s+([A-Za-z_][A-Za-z_0-9]*)\s*\{", t):
        name, i, depth = m.group(1), m.end() - 1, 0
