# ------------------------------------------------------------ map templates
ATTRS = {"type": r"__uint\(\s*type\s*,\s*([A-Za-z_0-9]+)\s*\)",
         "max_entries": r"__uint\(\s*max_entries\s*,\s*([^)]+)\)",
         "map_flags": r"__uint\(\s*map_flags\s*,\s*([^)]+)\)",
         "pinning": r"__uint\(\s*pinning\s*,\s*([^)]+)\)",
         "key_size": r"__uint\(\s*key_size\s*,\s*([^)]+)\)",
         "value_size": r"__uint\(\s*value_size\s*,\s*([^)]+)\)",
         "key": r"__type\(\s*key\s*,\s*([^)]+)\)",
         "value": r"__type\(\s*value\s*,\s*([^)]+)\)",
         "values": r"__array\(\s*values\s*,\s*([^)]+)\)"}

def parse_attrs(body):
    out = {}
    for k, rx in ATTRS.items():
        m = re.search(rx, body)
        if m: out[k] = re.sub(r"[\s\\]+", " ", m.group(1)).strip()
    return out

MAPDECL = re.compile(
    r"struct\s*\{(?P<body>.*?)\}\s*(?P<name>[A-Za-z_][A-Za-z_0-9]*)\s*SEC\(\"\.maps\"\)\s*;?",
    re.S)

def human_bytes_expr(s):
    """'16,777,216' -> '16 MiB each'; anything else is returned as written."""
    try:
        n = int(s.replace(",", ""))
    except ValueError:
        return s
    for u, d in (("GiB", 1 << 30), ("MiB", 1 << 20), ("KiB", 1 << 10)):
        if n >= d and n % d == 0: return f"{n // d} {u} each"
    return f"{n:,} B each"

def enum_defs():
    """Every enumerator's value, so a geometry written as KL_LAYER_MAX *
    KESTREL_PROTO_MAX resolves to the number the loader checks."""
    out = {}
    for e in ENUMS.values():
        nxt = 0
        for v in e["values"]:
            raw = (v.get("value") or "").strip()
            m = _INT.match(raw) if raw else None
            if m: nxt = int(m.group(1), 16) if m.group(1) else int(m.group(2))
            elif raw and SAFE.match(raw):
                try: nxt = int(eval(raw, {"__builtins__": {}}, {}))
                except Exception: pass
            out.setdefault(v["name"], str(nxt)); nxt += 1
    return out
_INT = re.compile(r"^\(?\s*(?:(0x[0-9a-fA-F]+)|(\d+))\s*[uUlL]*\s*\)?$")
ENUM_DEFS = enum_defs()

def resolve_consts(expr, defs):
    """Write a geometry expression as a number when the defines allow it."""
    e = expr
    for _ in range(8):
        e2 = re.sub(r"\b([A-Za-z_]\w*)\b",
                    lambda m: defs.get(m.group(1), ENUM_DEFS.get(m.group(1), m.group(1))), e)
        if e2 == e: break
        e = e2
    e = re.sub(r"(\d)[uUlL]+\b", r"\1", e)
    if SAFE.match(e) and re.search(r"\d", e):
        try:
            v = eval(e, {"__builtins__": {}}, {})
            if isinstance(v, int) and v >= 0: return f"{v:,}"
        except Exception:
            pass
    return expr

# guards left standing above a declaration (object defines only)
def guards_at(dd, pos):
    stack = []
    for at, _e, kind, expr in dd:
        if at > pos: break
        if kind == "ifdef":    stack.append(expr.split()[0] if expr else "")
        elif kind == "ifndef": stack.append("!" + (expr.split()[0] if expr else ""))
        elif kind == "if":
            g = re.findall(r"defined\s*\(?\s*([A-Za-z_][A-Za-z_0-9]*)", expr)
            stack.append(g[0] if len(g) == 1 and "!" not in expr else "")
        elif kind in ("elif", "else"):
            if stack: stack[-1] = ""
        elif kind == "endif":
            if stack: stack.pop()
    return [g for g in stack if g and g.startswith("KESTREL_OBJ_")]

