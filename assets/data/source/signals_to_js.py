def split_args(s, start):
    """args of a call whose '(' is at start-1; returns (list, end)."""
    depth, i, cur, out = 1, start, [], []
    while i < len(s) and depth:
        ch = s[i]
        if ch in "([": depth += 1
        elif ch in ")]":
            depth -= 1
            if depth == 0: break
        if depth == 1 and ch == ",":
            out.append("".join(cur).strip()); cur = []
        else:
            cur.append(ch)
        i += 1
    out.append("".join(cur).strip())
    return out, i

# callees whose first argument is an OUT parameter: passing the looked-up
# pointer (or a member of it) to one of these is a write through the map.
OUT_PARAM = (r"(?:__builtin_mem(?:set|cpy|move)|bpf_probe_read\w*|bpf_core_read\w*|"
             r"bpf_skb_load_bytes\w*|bpf_get_current_comm|bpf_d_path|bpf_get_func_arg\w*|"
             r"bpf_sysctl_get_\w+|bpf_snprintf\w*|bpf_ringbuf_(?:reserve|output|submit|discard)|"
             r"bpf_map_(?:update|delete)_elem|bpf_perf_event_read_value|bpf_get_stack\w*|"
             r"kestrel_help_(?:probe_read\w*|skb_load_bytes|get_current_comm|sysctl_get_\w+))")

def mutates(body, var):
    """Does the body write through `var`, the pointer a lookup returned?"""
    v = re.escape(var)
    member = rf"{v}\s*(?:->|\.)\s*\w+(?:\s*\[[^\]]*\])?(?:\s*(?:->|\.)\s*\w+(?:\s*\[[^\]]*\])?)*"
    pats = [
        rf"\*\s*{v}\s*(?:\+\+|--|[-+*/|&^%]?=(?!=))",
        rf"(?<![\w.>]){member}\s*(?:\+\+|--|[-+*/|&^%]?=(?!=))",
        rf"(?:\+\+|--)\s*\*?\s*(?:{member}|{v})\b",
        rf"__sync_fetch_and_\w+\s*\(\s*&\s*(?:{member}|{v})\s*[,)]",
        rf"{OUT_PARAM}\s*\(\s*&?\s*(?:{member}|{v})\s*[,)\[]",
    ]
    return any(re.search(p, body) for p in pats)

def scan_calls(body):
    """Yield (helper, args, pos) for every map helper call in `body`."""
    for m in CALL.finditer(body):
        name = m.group(1)
        args, end = split_args(body, m.end())
        yield name, args, m.start()

