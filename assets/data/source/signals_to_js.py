def describe_name(name):
    parts = [p for p in re.split(r"[_\d]+", name.split("[")[0]) if p]
    return " ".join(TOKENS.get(p, p) for p in parts)

TYPES_SEEN = set()

def example_for(struct, f):
    """(example literal, what it decodes to, basis)."""
    name = f["name"].split("[")[0]
    arr  = re.search(r"\[([^\]]*)\]", f["name"])
    ty   = re.sub(r"^const\s+", "", f["type"]).strip()
    note = (f.get("note") or "")
    fam  = const_family_of(struct, f)

    nt = note.strip().rstrip(".")
    if re.fullmatch(r"[A-Z][A-Z0-9_]+", nt) and nt in CONSTS:
        return str(CONSTS[nt]), f"{nt} = {CONSTS[nt]}.", "constants"

    if name.startswith(("_pad", "_rsv", "_reserved", "pad")) or re.fullmatch(r"pad\d*", name):
        return "0", "Padding. Never written; not part of the ABI.", "type"

    if ty.startswith(("struct ", "union ")):
        inner = ty.split()[-1]
        if inner == "bpf_timer":
            return "", "A bpf_timer: opaque to userspace, armed by bpf_timer_init and bpf_timer_start.", "type"
        return "", f"The members of {ty}" + (f", listed under its own entry." if inner in TYPES_SEEN else "."), "type"

    if fam and fam.startswith("enum:"):
        pairs = [(n, v) for n, v in enum_pairs(fam[5:]) if not n.endswith(("_COUNT", "_MAX", "_SLOTS", "_N"))]
        if pairs:
            n, v = pairs[min(1, len(pairs) - 1)]
            rest = ", ".join(f"{v2}={n2}" for n2, v2 in pairs[:5])
            return str(v), f"{n} — one of {rest}", "constants"
    if fam and fam in FAMILIES:
        vals = {k: v for k, v in FAMILIES[fam]["values"].items()
                if not k.endswith(("MAX", "COUNT", "SLOTS", "CAP", "NONE", "ROWS", "BYTES"))}
        if vals:
            if FAMILIES[fam]["bitmask"]:
                picked = sorted(vals.items(), key=lambda kv: kv[1])[:2]
                val = 0
                for _n, v in picked: val |= v
                names = " | ".join(fam + n for n, _v in picked)
                allnames = ", ".join(f"{fam}{n}=0x{v:x}" for n, v in
                                     sorted(vals.items(), key=lambda kv: kv[1])[:6])
                return f"0x{val:04x}", f"{names}. Bits: {allnames}", "constants"
            picked = sorted(vals.items(), key=lambda kv: kv[1])
            n, v = picked[min(1, len(picked) - 1)]
            rest = ", ".join(f"{v2}={n2}" for n2, v2 in picked[:5])
            return str(v), f"{fam}{n} — one of {rest}", "constants"

    if arr and ty in ("__u8", "char", "unsigned char"):
        if re.search(r"path|name|comm|exe|interp|args|filename|cwd|host|sni|argv|thread|ua|banner|qname", name):
            return '"/usr/bin/curl"', f"A NUL-terminated string, at most {arr.group(1)} bytes.", "type"
        if re.search(r"addr|ip|a$|mac|src|dst", name):
            return "c0 a8 01 0a …", f"{arr.group(1)} address bytes as on the wire.", "type"
        return "00 00 00 00 …", f"{arr.group(1)} raw bytes.", "type"
    if arr:
        return "[0, 0, …]", f"{arr.group(1)} × {ty}.", "type"

    bits = WIDTH.get(ty, 32)
    cap  = (1 << bits) - 1
    sat  = "saturates" in note.lower()

    if name.endswith(("_ns", "_boottime", "_ts")) or name in ("now", "enter_ts", "ts", "expires", "until"):
        stamp = bool(re.search(r"boottime|_ts$|^ts$|^created|^first|^last|start|enter|emit|_at$|expires|until", name))
        v = 812_345_678_901 if stamp else 1_450_000
        what = ("a point in time on the boot clock" if stamp else "a duration")
        return str(v), f"{human_ns(v)} — {what}, in nanoseconds, {bits}-bit.", "unit"
    if name.endswith(("_us",)):
        return "12000", "12.0 ms — a duration in microseconds.", "unit"
    if name.endswith(("_ms",)):
        return "1000", "1.00 s — a duration in milliseconds.", "unit"
    if name.endswith("_bytes") or name.startswith("bytes_") or name in ("count_bytes", "pos", "size"):
        v = 1_048_576
        return str(v), f"{human_bytes(v)} — a byte count, {bits}-bit.", "unit"
    if name.endswith(("_ino", "_inum")) or name in ("ino", "dir_ino", "inum"):
        return "3407875", f"An inode number, {bits}-bit. Stable across rename and hardlink.", "unit"
    if name.endswith(("_id",)) or name in ("cgroup_id", "node_id", "flow_id"):
        return "12406", f"An opaque {bits}-bit id; compare it, do not interpret it.", "unit"
    if name.endswith(("_hash", "cookie", "_digest", "digest", "lineage")) or name.startswith("hash"):
        return "0x4c968a90ace3649b", f"A {bits}-bit digest; an identity to join on, not a value to read.", "unit"
    if re.search(r"^(?:owner_|target_|self_)?(?:pid|tgid|ppid|tid|[eu]?uid|gid)(?:_at_exec)?$", name):
        return "1742", f"{describe_name(name).capitalize()}, {bits}-bit.", "unit"
    if name.endswith(("_port",)) or name in ("sport", "dport", "port", "lport", "rport"):
        return "443", f"A TCP/UDP port, {bits}-bit.", "unit"
    if name == "magic":
        return "0x9123683e", "The filesystem's s_magic (statfs f_type): 0x9123683e is btrfs.", "unit"
    if name in ("nr", "pending_nr"):
        return "59", "A syscall number on this architecture: 59 is execve on x86_64.", "unit"
    if re.search(r"count|hits|_n$|^n$|fanout|dests|depth|entries|events|switches|errors|drops|^level$|since_wake", name):
        v = 7
        extra = f" Saturates at {cap}: it is not decremented." if sat else ""
        return str(v), f"{_art(bits)} {bits}-bit counter — {describe_name(name)}.{extra}", "unit"
    if name.endswith(("_len", "_size")) or name in ("len",):
        return "64", f"A length in bytes, {bits}-bit.", "unit"
    if name in ("seq", "generation") or name.endswith(("_generation", "_seq", "_version")):
        return "3", f"{_art(bits)} {bits}-bit {describe_name(name)}; it only moves forward.", "unit"
    if name == "ver":
        return str(ABI_VER), f"KESTREL_ABI_VER: the ABI this record was written under.", "constants"

    return "0", f"{describe_name(name).capitalize()} — {bits}-bit {'unsigned' if ty.startswith('__u') or ty.startswith('__be') or ty in ('unsigned int','unsigned long') else 'signed'}.", "type"

