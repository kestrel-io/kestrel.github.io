def clean_prose_files(text):
    """Rewrite a quoted comment so it names no source file: the page's unit
    is the program and the map, not the file. A removal takes the
    preposition or separator that introduced it, so the sentence parses.
    Research notes (*.md under docs/) are citations and stay."""
    if not text or "." not in text:
        return text
    def swap(m):
        f = m.group(1)
        if f.endswith(".md"): return m.group(0)
        return "\x00"
    out = FILE_TOKEN.sub(swap, text)
    if "\x00" not in out:
        return out
    out = re.sub(r"\s*\(\s*\x00[^()]*\)", "", out)
    out = re.sub(r"\s+(?:in|by|from|at|to|of|under|with|via|than|inside|on|and|is|see)\s+\x00",
                 "", out, flags=re.IGNORECASE)
    out = re.sub(r"\s*[,;]\s*\x00", "", out)
    out = re.sub(r"\x00\s*[,;:]\s*", "", out)
    out = out.replace("\x00", "")
    out = re.sub(r"\(\s+", "(", out)
    out = re.sub(r"\s+([,.;:)])", r"\1", out)
    out = re.sub(r"\s{2,}", " ", out)
    return out.strip()

