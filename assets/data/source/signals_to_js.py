SAFE = re.compile(r"^[0-9()!&|<>=+\-*/% ]*$")

def _eval(expr, defs, known):
    """Evaluate a #if expression. Returns True / False / None (undecidable)."""
    e = expr
    e = re.sub(r"defined\s*\(\s*([A-Za-z_]\w*)\s*\)", lambda m: _d(m.group(1), defs, known), e)
    e = re.sub(r"defined\s+([A-Za-z_]\w*)", lambda m: _d(m.group(1), defs, known), e)
    for _ in range(4):
        e2 = re.sub(r"\b([A-Za-z_]\w*)\b",
                    lambda m: defs.get(m.group(1), m.group(1)), e)
        if e2 == e: break
        e = e2
    e = e.replace("&&", " and ").replace("||", " or ").replace("!=", " __NE__ ")
    e = re.sub(r"!", " not ", e).replace("__NE__", "!=")
    if re.search(r"[A-Za-z_]", e.replace(" and ", " ").replace(" or ", " ").replace(" not ", " ")):
        return None
    try:
        return bool(eval(e, {"__builtins__": {}}, {}))
    except Exception:
        return None

def _d(sym, defs, known):
    if sym in defs: return "1"
    if sym in known: return "0"
    if sym.startswith(("KESTREL_", "TELEMETRY_")): return "0"
    return sym            # undecidable -> leaves an identifier behind

def filter_by_gates(text, dd, gates, defs=None):
    """Blank the regions of `text` this program's defines exclude."""
    out = list(text)
    if defs is None: defs = {g: "1" for g in gates}
    known = set(ALLGATES)
    stack = []            # {state: True/False/None, done: bool, start: int}
    def blank(a, b):
        for i in range(a, min(b, len(out))):
            if out[i] != "\n": out[i] = " "
    for at, end, kind, expr in dd:
        if kind == "define":
            if stack and any(f["state"] is False for f in stack): continue
            m = re.match(r"([A-Za-z_]\w*)\s*(?:\(|$|\s)(.*)", expr)
            if m and "(" not in expr[:len(m.group(1)) + 1] and not m.group(1).endswith("_H"):
                val = m.group(2).strip()
                if val == "": defs[m.group(1)] = "1"
                elif SAFE.match(val): defs[m.group(1)] = "(" + val + ")"
                known.add(m.group(1))
            continue
        if kind in ("ifdef", "ifndef", "if"):
            if kind == "ifdef":   v = _eval("defined(%s)" % (expr.split() or [""])[0], defs, known)
            elif kind == "ifndef": v = _eval("!defined(%s)" % (expr.split() or [""])[0], defs, known)
            else:                  v = _eval(expr, defs, known)
            stack.append({"state": v, "done": v is True, "start": end})
            continue
        if not stack: continue
        fr = stack[-1]
        if fr["state"] is False:
            blank(fr["start"], at)
        if kind == "elif":
            v = None if fr["done"] else _eval(expr, defs, known)
            if fr["done"]: v = False
            fr["state"] = v
            fr["done"] = fr["done"] or (v is True)
            fr["start"] = end
        elif kind == "else":
            fr["state"] = False if fr["done"] else (None if fr["state"] is None else True)
            fr["start"] = end
        elif kind == "endif":
            stack.pop()
    return "".join(out)

KW_NOT_FN = {"if","for","while","switch","return","sizeof","do","else","case",
             "defined","__builtin_expect","typeof","_Static_assert"}

def functions_in(text):
    """name -> [body], for every function definition in `text`."""
    out = {}
    for m in re.finditer(r"\)\s*\{", text):
        # walk back to the matching '('
        j = m.start(); depth = 0; i = j
        while i >= 0:
            if text[i] == ")": depth += 1
            elif text[i] == "(":
                depth -= 1
                if depth == 0: break
            i -= 1
        if i < 0: continue
        k = i - 1
        while k >= 0 and text[k] in " \t\n\\": k -= 1
        e = k + 1
        while k >= 0 and (text[k].isalnum() or text[k] == "_"): k -= 1
        name = text[k + 1:e]
        if not name or name in KW_NOT_FN or name[0].isdigit(): continue
        # something must precede the name on the declaration (a return type)
        q = k
        while q >= 0 and text[q] in " \t\n\\*": q -= 1
        if q < 0 or not (text[q].isalnum() or text[q] in "_>"): continue
        if text[q] == ">" or (q > 0 and text[q - 1] == "."): continue
        o = m.end() - 1; depth = 0; jj = -1
        for t_ in range(o, len(text)):
            if text[t_] == "{": depth += 1
            elif text[t_] == "}":
                depth -= 1
                if depth == 0: jj = t_; break
        flat = text.find("\n}", o)
        if jj < 0 or (flat >= 0 and jj > flat + 1): jj = flat + 1
        if jj <= o: continue
        out.setdefault(name, []).append((text[o + 1: jj], k + 1))
    return out

IDENT = re.compile(r"\b([A-Za-z_]\w*)\s*\(")

def analyse(pr):
    """Returns {map_name: {'roles': set, 'sites': [...]}} for one program."""
    gates = set(pr["gates"])
    files = [pr["abs"]] + sorted(pr["inc_abs"])
    defs = {g: "1" for g in gates}
    for _pass in (0, 1):
        units = []
        for f in files:
            units.append((rel(f), filter_by_gates(CODE[f], DIRS[f], gates, defs)))
    own = units[0][1]
    # macro instantiations, substituted
    for mac, args in pr["insts"]:
        mm = MACROS.get(mac)
        if not mm: continue
        body = mm["body"].replace("\\\n", "\n")
        body = subst(strip_comments(body), mm["params"], args).replace("##", "")
        units.append((mm["file"] + " :: " + mac + "(" + args[0] + ")", body))

    funcs, roots = {}, set()
    for label, txt in units:
        for nm, bodies in functions_in(txt).items():
            for b, at in bodies:
                funcs.setdefault(nm, []).append((label, b))
                head = txt[max(0, at - 400):at]
                k = head.rfind("SEC(")
                if k >= 0:
                    tail = head[k:]
                    if ('SEC(".maps")' not in tail and 'SEC("license")' not in tail
                            and tail.count("{") == 0 and tail.count(";") == 0):
                        roots.add(nm)

    for sd in pr["secs"]:
        if sd["fn"]: roots.add(sd["fn"])
    # BPF_PROG()/BPF_KPROBE() wrappers name the function in the macro args
    for m in re.finditer(r"BPF_(?:PROG|KPROBE|KRETPROBE|KSYSCALL)\s*\(\s*([A-Za-z_]\w*)", own):
        roots.add(m.group(1))
    # timer callbacks are reached from bpf_timer_set_callback()
    for _l, txt in units:
        for m in re.finditer(r"bpf_timer_set_callback\s*\([^,]+,\s*([A-Za-z_]\w*)", txt):
            roots.add(m.group(1))
    for mac, args in pr["insts"]:
        for a in args:
            if re.fullmatch(r"[a-z_]\w*", a): roots.add(a)
    for nm, defs_ in MACRO_FUNCS.items():
        for label, body in defs_:
            funcs.setdefault(nm, []).append((label + " (macro)", body))
    roots &= set(funcs)
    reach, queue = set(roots), list(roots)
    while queue:
        fn = queue.pop()
        for label, body in funcs.get(fn, []):
            for m in IDENT.finditer(body):
                nm = m.group(1)
                if nm in funcs and nm not in reach:
                    reach.add(nm); queue.append(nm)
            # token-pasted macro calls (KESTREL_FV_CAST_##cast(...)) hide the
            # callee behind ##, so any known UPPERCASE macro named in the body
            # counts as reached.
            for m in re.finditer(r"\b(\w{3,})\b", body):
                nm = m.group(1)
                if nm in funcs and nm not in reach:
                    reach.add(nm); queue.append(nm)

    hits = {}
    def note(mapname, role, site):
        e = hits.setdefault(mapname, {"roles": set(), "sites": []})
        e["roles"].add(role)
        if site not in e["sites"]: e["sites"].append(site)

    for fn in sorted(reach):
        for label, body in funcs.get(fn, []):
            for helper, args, pos in scan_calls(body):
                spec = HELPERS.get(helper)
                if not spec:
                    spec = HELPERS.get(helper.replace("kestrel_help_", "bpf_"))
                if not spec: continue
                role, idx = spec
                if idx >= len(args): continue
                a = args[idx].strip()
                m = re.match(r"&\s*([A-Za-z_]\w*)$", a)
                if not m: continue
                mapname = m.group(1)
                if role == "storage":
                    flags = args[3] if len(args) > 3 else ""
                    r = WRITE if "F_CREATE" in flags else READ
                    note(mapname, r, {"fn": fn, "file": label, "helper": helper})
                    if r == WRITE:
                        note(mapname, READ, {"fn": fn, "file": label, "helper": helper})
                    continue
                note(mapname, role, {"fn": fn, "file": label, "helper": helper})
                if helper.endswith("lookup_elem") or helper.endswith("lookup_percpu_elem"):
                    before = body[:pos].replace("\n", " ")
                    mm = re.search(r"(?:^|[;{}()=])\s*([A-Za-z_][\w \t*]*?\b)?(\w+)\s*=\s*$", before)
                    if not mm: continue
                    decl, var = (mm.group(1) or ""), mm.group(2)
                    if not decl:   # assigned to a variable declared earlier
                        dm = re.search(r"\b((?:const\s+)?[\w]+(?:\s+\w+)*\s*\**)\s*%s\s*[;,=]"
                                       % re.escape(var), body)
                        decl = dm.group(1) if dm else ""
                    if "const" in decl: continue
                    tail = body[pos:]
                    if mutates(tail, var):
                        note(mapname, WRITE,
                             {"fn": fn, "file": label, "helper": "lookup + write-through"})
                    elif re.search(r"return\s*(?:\([^)]*\)\s*)?%s\s*;" % re.escape(var), tail):
                        note(mapname, WRITE,
                             {"fn": fn, "file": label,
                              "helper": "lookup returned as a writable pointer"})
    writes_ring = any("bpf_ringbuf_reserve(" in b or "bpf_ringbuf_output(" in b
                      for fn in reach for _l, b in funcs.get(fn, []))
    if writes_ring:
        for mapname, e in hits.items():
            rec = MAPS.get(mapname)
            if rec and rec["type"] == "ARRAY_OF_MAPS":
                e["roles"].add(WRITE)
                e["sites"].append({"fn": "dp_reserve", "file": "include/kestrel_data_plane.h",
                                   "helper": "bpf_ringbuf_reserve on the looked-up ring"})
    return hits, reach, funcs

